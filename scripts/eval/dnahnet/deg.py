#: Appendix-specified 15 nt cassette. Five stop codons back to back
#: (TAA TAA TAA TAG TGA) so that a stop is hit in any reading frame.
STOP_CASSETTE = "TAATAATAATAGTGA"

#: "we extracted an 8192-bp genomic window centered on the gene".
WINDOW_LENGTH = 8192

#: "12 bp downstream of the start codon". ASSUMPTION A3: read as a 0-based
#: offset from the first base of the start codon, so the cassette replaces
#: window bases [cds_start + 12, cds_start + 27). The competing reading
#: ("12 bp after the start codon ends") gives 15; both are in frame. Exposed
#: as ``--knockout-offset`` so the sensitivity is one flag away.
KNOCKOUT_OFFSET = 12

#: "sequence identity (>99%)" -- strictly greater than, as printed.
IDENTITY_THRESHOLD = 0.99

DEG_DOWNLOAD_BASE = "http://tubic.org/deg/public/download"
DEG_BACTERIA_FILES = (
  "deg_bacteria.csv.zip",      # one row per DEG essentiality experiment
  "deg_annotation_p.csv.zip",  # one row per prokaryote essential gene
  "DEG10.nt.gz",               # essential-gene nucleotide sequences
)

NCBI_EUTILS = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils"
USER_AGENT = "bd3lms-dnahnet-benchmark/1.0"

_COMPLEMENT = str.maketrans(
  "ACGTUNKRSWYMBDHVacgtunkrswymbdhv",
  "TGCAANMYSWRKVHDBtgcaanmyswrkvhdb")
_ACGTN_RE = re.compile(r"^[ACGTN]+$")


