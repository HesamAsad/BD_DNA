"""Reproducible DEG gene-essentiality helpers for the dnaHNet benchmark.

Protocol, quoted from Ma et al. (2026), "Zero-Shot Gene Essentiality
Prediction":

  "We generated binary essentiality labels for all 62 bacterial organisms in
   the Database of Essential Genes (DEG), with base sequences and annotations
   from NCBI. Genes matching DEG entries by name or sequence identity (>99%)
   were labeled essential. This dataset of 185226 data points evaluates the
   model's capacity to integrate broader genomic context and long-range
   dependencies."

  "For each gene, we extracted an 8192-bp genomic window centered on the gene
   to capture local context. Knockout variants were generated by inserting a
   15-bp stop codon sequence 12 bp downstream of the start codon (15
   nucleotides were replaced). The log-likelihood difference between wild-type
   and knockout sequences served as the predictor."

  Appendix: "The exact 15bp stop codon sequence used for the gene essentiality
   evaluations was the sequence TAATAATAATAGTGA."

Everything the paper leaves unspecified is a named constant or a CLI flag here
and is listed in ``docs/deg_benchmark_plan.md`` under "Assumptions". Nothing is
silently chosen.

This module deliberately mirrors ``scripts/eval/dnahnet/mavedb.py``: source
clients, record construction and metric helpers in one dependency-light place,
with ``prepare_deg.py`` / ``score_deg.py`` as thin drivers. ``rankdata`` is
imported from ``mavedb`` rather than duplicated.
"""

