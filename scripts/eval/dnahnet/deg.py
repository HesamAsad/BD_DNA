def roc_auc(labels: Sequence[int], scores: Sequence[float]) -> float:
  """Mann-Whitney AUROC with mid-rank tie handling.

  Sign-sensitive on purpose: a larger ``score`` must mean "more essential".
  Returns NaN when either class is empty.
  """
  labels = np.asarray(labels)
  scores = np.asarray(scores, dtype=np.float64)
  if labels.shape != scores.shape or labels.ndim != 1:
    raise ValueError("roc_auc requires two equal-length 1-D sequences")
  if not np.isfinite(scores).all():
    raise ValueError("roc_auc received a non-finite score")
  positive = labels.astype(bool)
  n_pos = int(positive.sum())
  n_neg = int(labels.size - n_pos)
  if n_pos == 0 or n_neg == 0:
    return float("nan")
  ranks = rankdata(scores)
  return float(
    (ranks[positive].sum() - n_pos * (n_pos + 1) / 2) / (n_pos * n_neg))


def _auroc_block(
    labels: Sequence[int],
    scores: Sequence[float],
    organisms: Sequence[str],
) -> dict:
  """Pooled AUROC, macro AUROC and the per-organism breakdown."""
  labels = np.asarray(labels)
  scores = np.asarray(scores, dtype=np.float64)
  organisms = np.asarray(organisms)
  pooled = roc_auc(labels, scores)
  per_organism = []
  for organism in sorted(set(organisms.tolist())):
    selection = organisms == organism
    per_organism.append({
      "organism_id": organism,
      "n": int(selection.sum()),
      "n_essential": int(labels[selection].sum()),
      "base_rate": float(labels[selection].mean()),
      "auroc": roc_auc(labels[selection], scores[selection]),
    })
  scored = [row["auroc"] for row in per_organism
            if math.isfinite(row["auroc"])]
  return {
    "pooled_auroc": pooled,
    "macro_auroc": float(np.mean(scored)) if scored else float("nan"),
    "macro_auroc_std": float(np.std(scored)) if scored else float("nan"),
    "num_scored_organisms": len(scored),
    "per_organism": per_organism,
  }


#: Model-free predictors. MANDATORY reporting: on MaveDB a zero-parameter
#: mutation-count feature beat every model, so a benchmark is not interpretable
#: until the trivial features are on the same page as the model number.
#: ``organism_base_rate`` is the between-organism confound made explicit: it is
#: constant within an organism, so its macro AUROC is 0.5 by construction while
#: its pooled AUROC can be far above 0.5.
BASELINE_FEATURES = {
  "gene_length": lambda row: float(row["gene_length"]),
  "negative_gene_length": lambda row: -float(row["gene_length"]),
  "window_gc": lambda row: float(row["window_gc"]),
  # Gene coordinate, not window_start: an origin-wrapping window starts near
  # the end of the contig even when its gene sits at position 409.
  "distance_from_contig_start": lambda row: float(row["gene_start"]),
  "organism_base_rate": None,   # filled in from the labels themselves
  "random": None,               # seeded control, must land at ~0.5
}


def baseline_scores(records: Sequence[Mapping], seed: int = 0) -> dict:
  labels = np.asarray([int(row["essential"]) for row in records])
  organisms = [str(row["organism_id"]) for row in records]
  base_rate = {}
  for organism in set(organisms):
    selection = [index for index, name in enumerate(organisms)
                 if name == organism]
    base_rate[organism] = float(labels[selection].mean())
  generator = np.random.default_rng(seed)
  scores = {}
  for name, feature in BASELINE_FEATURES.items():
    if name == "organism_base_rate":
      scores[name] = [base_rate[name_] for name_ in organisms]
    elif name == "random":
      scores[name] = generator.random(len(records)).tolist()
    else:
      scores[name] = [feature(row) for row in records]
  return scores


def summarize_deg_predictions(
    records: Sequence[Mapping],
    score_fields: Sequence[str] = ("essentiality_score",),
    headline_field: str = "essentiality_score",
    baseline_seed: int = 0,
) -> dict:
  """Pooled + macro AUROC for the model and for every model-free baseline."""
  records = list(records)
  if not records:
    raise ValueError("summarize_deg_predictions received no records")
  labels = [int(row["essential"]) for row in records]
  organisms = [str(row["organism_id"]) for row in records]

  variants = {}
  for field in score_fields:
    variants[field] = _auroc_block(
      labels, [float(row[field]) for row in records], organisms)

  baselines = {}
  for name, scores in baseline_scores(records, seed=baseline_seed).items():
    block = _auroc_block(labels, scores, organisms)
    baselines[name] = {
      "pooled_auroc": block["pooled_auroc"],
      "macro_auroc": block["macro_auroc"],
      "macro_auroc_std": block["macro_auroc_std"],
    }

  headline = variants[headline_field]
  n_essential = int(sum(labels))
  return {
    "num_genes": len(records),
    "num_organisms": len(set(organisms)),
    "num_essential": n_essential,
    "base_rate": n_essential / len(records),
    "headline_metric": "macro mean per-organism AUROC",
    "macro_auroc": headline["macro_auroc"],
    "macro_auroc_std": headline["macro_auroc_std"],
    "pooled_auroc": headline["pooled_auroc"],
    "num_scored_organisms": headline["num_scored_organisms"],
    # AUROC is sign-sensitive; publishing the flipped value makes an inverted
    # convention obvious at a glance instead of silently halving the claim.
    "macro_auroc_if_sign_flipped": (
      1.0 - headline["macro_auroc"]
      if math.isfinite(headline["macro_auroc"]) else float("nan")),
    "per_organism": headline["per_organism"],
    "score_variants": {
      field: {key: block[key] for key in
              ("pooled_auroc", "macro_auroc", "macro_auroc_std")}
      for field, block in variants.items()},
    "baselines": baselines,
  }


def write_jsonl_gz(path: Path, records: Iterable[Mapping]) -> tuple[int, str]:
  """Deterministic gzip JSONL (mtime=0), returning count and SHA-256."""
  import os
  import tempfile
  path.parent.mkdir(parents=True, exist_ok=True)
  with tempfile.NamedTemporaryFile("wb", dir=path.parent, delete=False) as raw:
    temporary = Path(raw.name)
    with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as compressed:
      with io.TextIOWrapper(compressed, encoding="utf-8") as text:
        count = 0
        for record in records:
          text.write(json.dumps(record, sort_keys=True, separators=(",", ":")))
          text.write("\n")
          count += 1
  digest = sha256_file(temporary)
  os.replace(temporary, path)
  return count, digest


def iter_jsonl_gz(path: Path) -> Iterator[dict]:
  """Alias of :func:`read_jsonl_gz` kept for symmetry with the writer."""
  return read_jsonl_gz(path)
