def normalize_accessions(text: str) -> tuple[str, ...]:
  """DEG separates replicons with ',', ';' or whitespace, versions optional."""
  parts = re.split(r"[;,\s]+", (text or "").strip())
  cleaned = []
  for part in parts:
    part = part.strip()
    if not part or part == "-":
      continue
    cleaned.append(part.split(".")[0])
  return tuple(sorted(set(cleaned)))


def load_deg_organisms(path: Path) -> list[dict]:
  rows = read_zipped_csv(path, "deg_bacteria.csv")
  organisms = []
  for row in rows:
    if len(row) < 14:
      raise ValueError(f"Unexpected deg_bacteria.csv row width: {len(row)}")
    entry = {
      key: row[index].strip() for key, index in _ORGANISM_COLUMNS.items()}
    entry["accessions"] = normalize_accessions(entry["accession"])
    organisms.append(entry)
  return organisms


def load_deg_annotations(path: Path) -> list[dict]:
  rows = read_zipped_csv(path, "deg_annotation_p.csv")
  annotations = []
  for row in rows:
    if len(row) < 13:
      raise ValueError(f"Unexpected deg_annotation_p.csv row width: {len(row)}")
    annotations.append({
      key: row[index].strip() for key, index in _ANNOTATION_COLUMNS.items()})
  return annotations


def load_deg_nucleotides(path: Path) -> dict[str, str]:
  """DEG10.nt.gz keyed by DEG gene accession (``>DEG10010001``)."""
  sequences: dict[str, str] = {}
  name = None
  chunks: list[str] = []
  with gzip.open(path, "rt", errors="replace") as handle:
    for line in handle:
      if line.startswith(">"):
        if name is not None:
          sequences[name] = "".join(chunks).upper()
        name = line[1:].strip().split()[0]
        chunks = []
      else:
        chunks.append(line.strip())
  if name is not None:
    sequences[name] = "".join(chunks).upper()
  return sequences


def gene_name_aliases(raw: str) -> set[str]:
  """DEG packs synonyms as ``tmk/tdk`` or ``metS,metG``; split them out."""
  aliases = set()
  for part in re.split(r"[/,;|]", (raw or "")):
    part = part.strip().lower()
    if part and part != "-":
      aliases.add(part)
  return aliases


def feature_name_keys(qualifiers: Mapping[str, Sequence[str]]) -> set[str]:
  keys = set()
  for field in ("gene", "locus_tag", "old_locus_tag", "gene_synonym"):
    for value in qualifiers.get(field, ()):
      keys |= gene_name_aliases(value)
  return keys


def sequence_identity(left: str, right: str) -> float:
  """Ungapped identity over equal-length sequences.

  ASSUMPTION A2: the paper's ">99% sequence identity" almost certainly came
  from a gapped aligner (BLAST). No BLAST binary is installed on this cluster,
  so matching is exact-or-ungapped: identical sequences, or equal-length
  sequences differing at <1% of positions, on either strand. Measured recall
  against DEG1001 (B. subtilis 168): 260/271 by sequence alone, 268/271 when
  unioned with name matching.
  """
  if len(left) != len(right) or not left:
    return 0.0
  return 1.0 - hamming_positions(left, right) / len(left)


class EssentialGeneMatcher:
  """Labels annotated CDS features against one organism's DEG entries."""

  def __init__(
      self,
      deg_names: Iterable[str],
      deg_sequences: Iterable[str],
      identity_threshold: float = IDENTITY_THRESHOLD,
  ):
    self.identity_threshold = identity_threshold
    self.names: set[str] = set()
    for raw in deg_names:
      self.names |= gene_name_aliases(raw)
    self.exact: set[str] = set()
    self.by_length: dict[int, list[str]] = defaultdict(list)
    for sequence in deg_sequences:
      sequence = (sequence or "").upper()
      if not sequence:
        continue
      for variant in (sequence, reverse_complement(sequence)):
        if variant not in self.exact:
          self.exact.add(variant)
          self.by_length[len(variant)].append(variant)

  def match(self, name_keys: set[str], cds_sequence: str) -> str:
    """Returns ``'name'``, ``'sequence'``, ``'both'`` or ``'none'``."""
    by_name = bool(name_keys & self.names)
    by_sequence = False
    cds_sequence = (cds_sequence or "").upper()
    if cds_sequence:
      if cds_sequence in self.exact:
        by_sequence = True
      else:
        for candidate in self.by_length.get(len(cds_sequence), ()):
          if sequence_identity(
              candidate, cds_sequence) > self.identity_threshold:
            by_sequence = True
            break
    if by_name and by_sequence:
      return "both"
    if by_name:
      return "name"
    if by_sequence:
      return "sequence"
    return "none"


