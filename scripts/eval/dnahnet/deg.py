class NCBIClient:
  """Read-only E-utilities client, no extra dependency, bounded retries.

  ``rettype=gbwithparts`` returns annotation and sequence in one document, so
  a single request per replicon pins both. Responses are streamed to disk;
  nothing larger than a chunk is held in memory (the head node has a ~1.7 GB
  per-process cgroup).
  """

  def __init__(
      self,
      eutils_base: str = NCBI_EUTILS,
      timeout: float = 300.0,
      retries: int = 4,
      api_key: str | None = None,
      min_interval: float = 0.4,
  ):
    self.eutils_base = eutils_base.rstrip("/")
    self.timeout = timeout
    self.retries = retries
    self.api_key = api_key
    self.min_interval = min_interval
    self._last_request = 0.0

  def _throttle(self):
    elapsed = time.monotonic() - self._last_request
    if elapsed < self.min_interval:
      time.sleep(self.min_interval - elapsed)
    self._last_request = time.monotonic()

  def fetch_genbank(self, accession: str, destination: Path) -> Path:
    """Downloads ``accession`` as gzip-compressed GenBank flat file."""
    query = [
      ("db", "nuccore"), ("id", accession),
      ("rettype", "gbwithparts"), ("retmode", "text")]
    if self.api_key:
      query.append(("api_key", self.api_key))
    url = f"{self.eutils_base}/efetch.fcgi?{urllib.parse.urlencode(query)}"
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    destination.parent.mkdir(parents=True, exist_ok=True)
    last_error = None
    for attempt in range(self.retries):
      self._throttle()
      temporary = destination.with_suffix(destination.suffix + ".partial")
      try:
        with urllib.request.urlopen(request, timeout=self.timeout) as response:
          with gzip.open(temporary, "wb") as sink:
            first = b""
            while True:
              chunk = response.read(1 << 20)
              if not chunk:
                break
              if not first:
                first = chunk[:16]
              sink.write(chunk)
        if not first.startswith(b"LOCUS"):
          raise RuntimeError(
            f"NCBI returned a non-GenBank body for {accession}: {first!r}")
        temporary.replace(destination)
        return destination
      except Exception as error:  # noqa: BLE001 - retried and re-raised below
        last_error = error
        temporary.unlink(missing_ok=True)
        if attempt + 1 < self.retries:
          time.sleep(2 ** attempt)
    raise RuntimeError(
      f"NCBI efetch failed for {accession}") from last_error


