def sha256_file(path: Path) -> str:
  digest = hashlib.sha256()
  with path.open("rb") as handle:
    for chunk in iter(lambda: handle.read(1 << 20), b""):
      digest.update(chunk)
  return digest.hexdigest()


def read_zipped_csv(path: Path, member: str) -> list[list[str]]:
  """DEG ships semicolon-delimited, fully quoted CSV inside a zip."""
  with zipfile.ZipFile(path) as archive:
    payload = archive.read(member).decode("utf-8", errors="replace")
  return [
    row for row in csv.reader(
      io.StringIO(payload), delimiter=";", quotechar='"')
    if row and any(field.strip() for field in row)]


