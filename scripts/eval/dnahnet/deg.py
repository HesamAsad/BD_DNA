def reverse_complement(sequence: str) -> str:
  return sequence.translate(_COMPLEMENT)[::-1]


def gc_content(sequence: str) -> float:
  counts = {base: sequence.count(base) for base in "ACGT"}
  total = sum(counts.values())
  if total == 0:
    return float("nan")
  return (counts["G"] + counts["C"]) / total


def centered_window_start(
    contig_length: int,
    gene_start: int,
    gene_end: int,
    window_length: int = WINDOW_LENGTH,
    circular: bool = True,
) -> tuple[int, bool]:
  """First plus-strand base of the window centred on ``[gene_start, gene_end)``.

  Returns ``(window_start, clamped)``. ``window_start`` may be negative or run
  past ``contig_length`` when the contig is circular; :func:`extract_window`
  resolves the wrap. On a linear contig the window is clamped inward so it
  still has exactly ``window_length`` bases (ASSUMPTION A5).
  """
  if contig_length < window_length:
    raise ValueError(
      f"Contig of {contig_length} nt is shorter than the {window_length} nt "
      "window")
  if not 0 <= gene_start < gene_end <= contig_length:
    raise ValueError(
      f"Gene span [{gene_start}, {gene_end}) outside contig of "
      f"{contig_length} nt")
  centre = (gene_start + gene_end) // 2
  start = centre - window_length // 2
  if circular:
    return start, False
  clamped = min(max(start, 0), contig_length - window_length)
  return clamped, clamped != start


def extract_window(
    contig: str,
    window_start: int,
    window_length: int = WINDOW_LENGTH,
) -> str:
  """Plus-strand window, wrapping modulo the contig for circular replicons."""
  contig_length = len(contig)
  if contig_length < window_length:
    raise ValueError("Contig is shorter than the window")
  start = window_start % contig_length
  end = start + window_length
  if end <= contig_length:
    return contig[start:end]
  return contig[start:] + contig[:end - contig_length]


def project_position(
    plus_position: int,
    window_start: int,
    contig_length: int,
    window_length: int = WINDOW_LENGTH,
) -> int:
  """Plus-strand contig coordinate -> offset inside the extracted window."""
  return (plus_position - window_start) % contig_length


def build_window_record(
    contig: str,
    gene_start: int,
    gene_end: int,
    strand: int,
    window_length: int = WINDOW_LENGTH,
    knockout_offset: int = KNOCKOUT_OFFSET,
    cassette: str = STOP_CASSETTE,
    circular: bool = True,
    orientation: str = "gene",
) -> dict:
  """Window geometry for one gene, in the requested reading orientation.

  ``orientation='gene'`` (default, ASSUMPTION A4) returns the window
  reverse-complemented for minus-strand genes, so the coding sequence reads
  5'->3' and the cassette appears literally as ``STOP_CASSETTE`` at a fixed
  offset for every gene. ``orientation='reference'`` keeps the plus strand and
  writes the reverse complement of the cassette instead.

  Raises ``ValueError`` when the knockout site falls outside the window, which
  happens only for genes longer than the window (ASSUMPTION A6).
  """
  if strand not in (1, -1):
    raise ValueError(f"strand must be +1 or -1, got {strand!r}")
  if orientation not in ("gene", "reference"):
    raise ValueError(f"orientation must be 'gene' or 'reference'")
  contig_length = len(contig)
  window_start, clamped = centered_window_start(
    contig_length, gene_start, gene_end, window_length, circular)
  plus_window = extract_window(contig, window_start, window_length)
  wrapped = circular and not (
    0 <= window_start and window_start + window_length <= contig_length)

  # First base of the start codon, in plus-strand contig coordinates.
  cds_first_base = gene_start if strand == 1 else gene_end - 1
  plus_offset = project_position(
    cds_first_base, window_start, contig_length, window_length)

  if orientation == "gene" and strand == -1:
    window = reverse_complement(plus_window)
    cds_offset = window_length - 1 - plus_offset
    written = cassette
    step = 1
  elif orientation == "gene":
    window = plus_window
    cds_offset = plus_offset
    written = cassette
    step = 1
  elif strand == -1:                      # reference orientation, minus gene
    window = plus_window
    cds_offset = plus_offset
    written = reverse_complement(cassette)
    step = -1
  else:                                   # reference orientation, plus gene
    window = plus_window
    cds_offset = plus_offset
    written = cassette
    step = 1

  if step == 1:
    cassette_start = cds_offset + knockout_offset
  else:
    # Walking 3'-ward along the gene means walking left along the plus strand.
    cassette_start = cds_offset - knockout_offset - len(cassette) + 1
  if cassette_start < 0 or cassette_start + len(cassette) > window_length:
    raise ValueError(
      "Knockout site falls outside the centred window (gene longer than the "
      f"window): cassette_start={cassette_start}, window={window_length}")

  return {
    "window_start": window_start % contig_length,
    "window_sequence": window,
    "window_wrapped": bool(wrapped),
    "window_clamped": bool(clamped),
    "cds_offset": int(cds_offset),
    "cassette_start": int(cassette_start),
    "cassette": written,
    "orientation": orientation,
  }


def apply_knockout(
    window_sequence: str,
    cassette_start: int,
    cassette: str = STOP_CASSETTE,
) -> str:
  """Length-preserving substitution of ``cassette`` into ``window_sequence``.

  The paper says "inserting a 15-bp stop codon sequence ... (15 nucleotides
  were replaced)": the total length is unchanged.
  """
  end = cassette_start + len(cassette)
  if cassette_start < 0 or end > len(window_sequence):
    raise ValueError("Cassette does not fit inside the window")
  mutated = (
    window_sequence[:cassette_start] + cassette + window_sequence[end:])
  if len(mutated) != len(window_sequence):
    raise AssertionError("Knockout changed the sequence length")
  return mutated


def knockout_from_record(record: Mapping) -> str:
  return apply_knockout(
    record["window_sequence"],
    int(record["cassette_start"]),
    record.get("cassette", STOP_CASSETTE))


def hamming_positions(left: str, right: str) -> int:
  if len(left) != len(right):
    raise ValueError("hamming_positions requires equal lengths")
  return sum(1 for a, b in zip(left, right) if a != b)


